class TranslatorEngine:
    def __init__(self):
        self.buffer = []
        self.last_sign = None
        self.last_sign_count = 0
        self.MIN_HOLD_FRAMES = 3 # Require 3 consecutive frames to confirm sign

    def process_prediction(self, prediction, confidence):
        """
        Filters noise by requiring gesture stability across consecutive frames.
        """
        if confidence < 0.55 or prediction == "UNKNOWN":
            # An unstable frame breaks the consecutive-frame hold requirement.
            self.last_sign = None
            self.last_sign_count = 0
            return {"status": "unstable", "current_word": "".join(self.buffer)}

        if prediction == self.last_sign:
            self.last_sign_count += 1
        else:
            self.last_sign = prediction
            self.last_sign_count = 1

        if self.last_sign_count == self.MIN_HOLD_FRAMES:
            # Confirmed sign
            if len(prediction) == 1: # Single letter/number
                self.buffer.append(prediction)
            else: # Word / phrase
                if len(self.buffer) > 0 and self.buffer[-1] != " ":
                    self.buffer.append(" ")
                self.buffer.append(prediction)
                self.buffer.append(" ")

            return {
                "status": "added",
                "added": prediction,
                "current_word": "".join(self.buffer)
            }

        return {"status": "holding", "current_word": "".join(self.buffer)}

    def add_space(self):
        self.buffer.append(" ")
        return "".join(self.buffer)

    def reset_stability(self):
        self.last_sign = None
        self.last_sign_count = 0

    def backspace(self):
        if len(self.buffer) > 0:
            self.buffer.pop()
        return "".join(self.buffer)

    def clear(self):
        self.buffer = []
        self.reset_stability()
        return ""

translator_engine = TranslatorEngine()
